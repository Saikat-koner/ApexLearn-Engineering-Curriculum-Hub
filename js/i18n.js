let currentLang = localStorage.getItem('apex_language') || 'en';

function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('apex_language', lang);

  // Update text nodes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('placeholder', translations[lang][key]);
    }
  });

  // Update select dropdown value
  const select = document.getElementById('langSelect');
  if (select && select.value !== lang) {
    select.value = lang;
  }

  // Re-render subjects so buttons and badges pick up current language
  if (typeof renderSubjects === 'function') {
    renderSubjects();
  }
}

function t(key) {
  if (translations[currentLang] && translations[currentLang][key]) {
    return translations[currentLang][key];
  }
  if (translations.en && translations.en[key]) {
    return translations.en[key];
  }
  return key;
}

// Attach listener on DOMContentLoaded
document.addEventListener('DOMContentLoaded', () => {
  const select = document.getElementById('langSelect');
  if (select) {
    select.value = currentLang;
    select.addEventListener('change', (e) => {
      setLanguage(e.target.value);
    });
  }
  setLanguage(currentLang);
});
